"""Contract: the shipped type stub packaging/_flow.pyi covers every public name of peclet.flow._flow.

The stub is generated by nanobind.stubgen against an MPI-enabled host build (recipe in
CMakeLists.txt, next to the rule that stages it). A binding added without regenerating it fails
here. Names in the stub but absent at runtime fail too, except on a build without MPI, which lacks
the distributed names the stub carries.

Run: PYTHONPATH=<build> python -m pytest -q tests/python/test_stub_sync.py
"""
import ast
from pathlib import Path

from peclet.flow import _flow

STUB = Path(__file__).resolve().parents[2] / "packaging" / "_flow.pyi"
# Bound only under PECLET_FLOW_MPI (src/flow_bindings.cpp).
MPI_ONLY = {"mpi_block", "predict_hierarchy", "Solver.init_mpi", "SolverColocated.init_mpi",
            "SolverDiagnostics.rebalance_by_weights",
            "SolverColocatedDiagnostics.rebalance_by_weights"}


def _public(name):
    return not name.startswith("_") or name == "__init__"


def _stub_names():
    tree = ast.parse(STUB.read_text())
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
        if isinstance(node, ast.ClassDef):
            for member in node.body:
                if isinstance(member, ast.FunctionDef) and _public(member.name):
                    names.add(f"{node.name}.{member.name}")
    return names


def _runtime_names():
    names = set()
    for name in dir(_flow):
        if name.startswith("_"):
            continue
        names.add(name)
        obj = getattr(_flow, name)
        if isinstance(obj, type):
            # A class without a bound constructor (the diagnostics tiers) still has nanobind's
            # refusing __init__, which carries no signature and is not part of the API.
            names.update(f"{name}.{m}" for m, v in vars(obj).items()
                         if _public(m) and (m != "__init__" or hasattr(v, "__nb_signature__")))
    return names


def test_stub_covers_every_public_name():
    missing = sorted(_runtime_names() - _stub_names())
    assert not missing, (f"public names of peclet.flow._flow missing from {STUB.name}: {missing}; "
                         "regenerate the stub (recipe in CMakeLists.txt)")


def test_stub_names_exist_at_runtime():
    extra = _stub_names() - _runtime_names()
    if not _flow.has_mpi:  # a build without MPI: the stub lists more
        extra -= MPI_ONLY
    assert not extra, f"names in {STUB.name} that peclet.flow._flow does not define: {sorted(extra)}"
